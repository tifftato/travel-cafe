export const GLYPH_ROWS = 7

// 'É' → 'E'처럼 악센트를 떼고 대문자로 바꿔서 폰트에 있는 글리프로 맞춥니다.
// 폰트에 없는 문자는 빈칸으로 처리(깨진 점 대신 공백이 덜 거슬림).
export function glyphFor(ch) {
  const c = ch.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toUpperCase()
  return G[c] || G[' ']
}

// 글자 사이 1열 간격을 포함한 전체 열 수 (캔버스 폭 계산용)
export function measureCols(text) {
  const chars = [...text]
  if (!chars.length) return 0
  return chars.reduce((sum, ch) => sum + glyphFor(ch)[0].length, 0) + (chars.length - 1)
}
